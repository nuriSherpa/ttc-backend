#!/bin/bash
: "${APP_DB_PASSWORD:?}" "${RT_DB_PASSWORD:?}"

psql -v ON_ERROR_STOP=1 -U "$POSTGRES_USER" -d "$POSTGRES_DB" \
     -v app_pw="$APP_DB_PASSWORD" -v rt_pw="$RT_DB_PASSWORD" <<'SQL'
CREATE ROLE ttc_app LOGIN PASSWORD :'app_pw';
CREATE ROLE ttc_rt  LOGIN PASSWORD :'rt_pw';

GRANT USAGE ON SCHEMA ops, ref, cur, rt TO ttc_app, ttc_rt;
GRANT SELECT ON ops.feed TO ttc_app, ttc_rt;

GRANT SELECT ON ALL TABLES IN SCHEMA ref, cur, rt TO ttc_app;

GRANT SELECT ON ALL TABLES IN SCHEMA ref TO ttc_rt;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA rt TO ttc_rt;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA rt TO ttc_rt;

ALTER DEFAULT PRIVILEGES IN SCHEMA rt GRANT SELECT ON TABLES TO ttc_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA rt
    GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO ttc_rt;
ALTER DEFAULT PRIVILEGES IN SCHEMA rt GRANT USAGE ON SEQUENCES TO ttc_rt;
SQL
